import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { RegistryError } from "./types.js";
import { normalizeYarnLockfile, parseYarnLockfile } from "./yarn-lockfile.js";

const PROXY = "http://wardby-proxy:8787/registry/npm/";
const fixture = (name: string) => readFileSync(new URL(`./fixtures/lockfiles/${name}`, import.meta.url), "utf8");
const parse = (body: string, maxEntries = 100) => parseYarnLockfile(body, { maxEntries, proxyRegistryUrl: PROXY });

function failure(fn: () => unknown): [number, string] | string {
  try {
    fn();
  } catch (error) {
    return error instanceof RegistryError ? [error.status, error.code] : String(error);
  }
  return "no error";
}

// What the fixtures lock (written by yarn 1.22 and yarn 4 for the same
// package.json as the pnpm fixtures).
const FIXTURE_VERSIONS = [
  "@sindresorhus/is@4.6.0",
  "ansi-regex@5.0.1",
  "debug@4.4.3",
  "emoji-regex@8.0.0",
  "is-fullwidth-code-point@3.0.0",
  "ms@2.1.3",
  "string-width@4.2.3",
  "strip-ansi@6.0.1",
];

describe("parseYarnLockfile: yarn classic (v1)", () => {
  it("reads a real yarn.lock: registry entries with npm integrity, resolved by descriptor", () => {
    const parsed = parse(fixture("yarn-v1.lock"));
    expect(parsed.integrity).toBeUndefined();
    expect(parsed.entries.map((entry) => `${entry.name}@${entry.version}`).sort()).toEqual(FIXTURE_VERSIONS);
    expect(parsed.entries.every((entry) => entry.kind === "registry")).toBe(true);
    expect(parsed.entries.find((entry) => entry.name === "ms")?.integrity).toBe(
      "sha512-6FlzubTLZG3J2a/NVCAleEhjzq5oxgHyaCU9yYXvcLsvoVaHJq/s5xXI6/XXP6tz7R9xAOtHnSO/tXtF3WRTlA==",
    );
    expect(parsed.resolve("debug@^4.3.0", "ms")).toMatchObject({ name: "ms", version: "2.1.3" });
    // The alias entry installs its target and resolves its own dependencies.
    const alias = "string-width-cjs@npm:string-width@^4.2.0";
    expect(parsed.entries.find((entry) => entry.path === alias)).toMatchObject({ name: "string-width" });
    expect(parsed.resolve(alias, "strip-ansi")).toMatchObject({ name: "strip-ansi", version: "6.0.1" });
    expect(parsed.resolve("debug@^4.3.0", "supports-color")).toBeUndefined();
  });

  const classic = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@s/parent@^1.0.0", "@s/parent@^1.1.0":
  version "1.1.0"
  resolved "${PROXY}-/tarball/%40s%2Fparent/1.1.0#0123456789abcdef0123456789abcdef01234567"
  integrity sha512-parent
  dependencies:
    child "~2.0.0"
    git-dep "github:x/y"
    local "file:../local"
  optionalDependencies:
    url-dep "^1.0.0"

child@~2.0.0:
  version "2.0.3"
  resolved "https://registry.npmjs.org/child/-/child-2.0.3.tgz"

"git-dep@github:x/y":
  version "1.0.0"
  resolved "https://codeload.github.com/x/y/tar.gz/abc"

url-dep@^1.0.0:
  version "1.0.0"
  resolved "https://example.com/url-dep-1.0.0.tgz#abc"
  integrity sha512-u

"local@file:../local":
  version "0.0.0"
`;

  it("classifies entries, resolves through either descriptor, and skips local packages", () => {
    const parsed = parse(classic);
    expect(Object.fromEntries(parsed.entries.map((entry) => [entry.path, entry.kind]))).toEqual({
      "@s/parent@^1.0.0": "registry",
      "child@~2.0.0": "registry",
      "git-dep@github:x/y": "unsupported",
      "url-dep@^1.0.0": "unsupported",
    });
    expect(parsed.entries.find((entry) => entry.name === "child")?.integrity).toBeNull();
    expect(parsed.resolve("@s/parent@^1.0.0", "child")).toMatchObject({ name: "child", version: "2.0.3" });
    expect(parsed.resolve("@s/parent@^1.0.0", "url-dep")).toMatchObject({ kind: "unsupported" });
    expect(parsed.resolve("@s/parent@^1.0.0", "local")).toBeUndefined();
    expect(parsed.resolve("child@~2.0.0", "anything")).toBeUndefined();
  });

  it("refuses malformed text, duplicate descriptors and too many entries", () => {
    const header = "# yarn lockfile v1\n\n";
    expect(failure(() => parse(`${header}a@^1:\n  version "1.0.0\n`))).toEqual([400, "wardby_bad_request"]);
    expect(failure(() => parse(`${header}a@^1:\n      version "1.0.0"\n`))).toEqual([400, "wardby_bad_request"]);
    expect(failure(() => parse(`${header}  version "1.0.0"\n`))).toEqual([400, "wardby_bad_request"]);
    expect(failure(() => parse(`${header}a@^1:\n  version "1.0.0"\n\n"a@^1", b@^2:\n  version "1.0.0"\n`))).toEqual([
      400,
      "wardby_bad_request",
    ]);
    expect(failure(() => parse(classic, 3))).toEqual([413, "wardby_lockfile_too_large"]);
  });

  it("stands in for the projects with the descriptors no entry depends on", () => {
    const body = `# yarn lockfile v1

a@^1.0.0:
  version "1.0.0"
  resolved "https://registry.yarnpkg.com/a/-/a-1.0.0.tgz"
  integrity sha512-a1
  dependencies:
    b "^1.0.0"

a@^2.0.0:
  version "2.0.0"
  resolved "https://registry.yarnpkg.com/a/-/a-2.0.0.tgz"
  integrity sha512-a2

b@^1.0.0:
  version "1.0.0"
  resolved "https://registry.yarnpkg.com/b/-/b-1.0.0.tgz"
  integrity sha512-b
`;
    const parsed = parse(body);
    // Two workspaces declare a at different ranges: one project each.
    expect(parsed.projects).toEqual([
      { path: ".", dependencies: [{ key: "a", name: "a", range: "^1.0.0" }] },
      { path: ".#1", dependencies: [{ key: "a", name: "a", range: "^2.0.0" }] },
    ]);
    expect(parsed.resolve(".", "a")).toMatchObject({ version: "1.0.0" });
    expect(parsed.resolve(".#1", "a")).toMatchObject({ version: "2.0.0" });
    expect(parsed.resolve(".", "b")).toBeUndefined();
  });
});

describe("parseYarnLockfile: yarn Berry", () => {
  it("reads a real yarn.lock: exact name@version entries, integrity left to the registry", () => {
    const parsed = parse(fixture("yarn-berry.lock"));
    expect(parsed.integrity).toBe("registry");
    expect(parsed.entries.map((entry) => `${entry.name}@${entry.version}`).sort()).toEqual(FIXTURE_VERSIONS);
    expect(parsed.entries.every((entry) => entry.kind === "registry" && entry.integrity === null)).toBe(true);
    expect(parsed.resolve("debug@npm:^4.3.0", "ms")).toMatchObject({ name: "ms", version: "2.1.3" });
    const alias = "string-width-cjs@npm:string-width@^4.2.0";
    expect(parsed.entries.find((entry) => entry.path === alias)).toMatchObject({ name: "string-width" });
    expect(parsed.resolve(alias, "emoji-regex")).toMatchObject({ name: "emoji-regex", version: "8.0.0" });
    expect(parsed.projects).toEqual([
      {
        path: "wardby-lockfile-fixture@workspace:.",
        dependencies: [
          { key: "@sindresorhus/is", name: "@sindresorhus/is", range: "^4.6.0" },
          { key: "debug", name: "debug", range: "^4.3.0" },
          { key: "string-width-cjs", name: "string-width", range: "^4.2.0" },
        ],
      },
    ]);
  });

  const berry = `__metadata:
  version: 6
  cacheKey: 8

"parent@npm:^1.0.0":
  version: 1.0.0
  resolution: "parent@npm:1.0.0"
  dependencies:
    fsevents: ~2.3.2
    typescript: "patch:typescript@npm%3A^5.0.0#~builtin<compat/typescript>"
    sibling: "workspace:^"
    git-dep: "github:x/y"
    url-dep: "npm:1.0.0"
  checksum: 10c0/abc
  languageName: node
  linkType: hard

"fsevents@npm:~2.3.2":
  version: 2.3.3
  resolution: "fsevents@npm:2.3.3"

"fsevents@patch:fsevents@npm%3A~2.3.2#~builtin<compat/fsevents>":
  version: 2.3.3
  resolution: "fsevents@patch:fsevents@npm%3A2.3.3#~builtin<compat/fsevents>::version=2.3.3&hash=df0bf1"

"typescript@npm:^5.0.0":
  version: 5.4.5
  resolution: "typescript@npm:5.4.5"

"typescript@patch:typescript@npm%3A^5.0.0#~builtin<compat/typescript>":
  version: 5.4.5
  resolution: "typescript@patch:typescript@npm%3A5.4.5#~builtin<compat/typescript>::version=5.4.5&hash=5adc0c"

"git-dep@github:x/y":
  version: 1.0.0
  resolution: "git-dep@https://github.com/x/y.git#commit=abc"

"url-dep@npm:1.0.0":
  version: 1.0.0
  resolution: "url-dep@npm:1.0.0::__archiveUrl=https%3A%2F%2Fexample.com%2Furl-dep-1.0.0.tgz"

"proxied@npm:1.0.0":
  version: 1.0.0
  resolution: "proxied@npm:1.0.0::__archiveUrl=${encodeURIComponent(`${PROXY}-/tarball/proxied/1.0.0`)}"

"sibling@workspace:^, sibling@workspace:packages/sibling":
  version: 0.0.0-use.local
  resolution: "sibling@workspace:packages/sibling"
  dependencies:
    parent: "npm:^1.0.0"
  languageName: unknown
  linkType: soft
`;

  it("classifies entries: npm resolutions (archive URLs checked), patches and workspaces local, others refused", () => {
    const parsed = parse(berry);
    expect(Object.fromEntries(parsed.entries.map((entry) => [entry.path, entry.kind]))).toEqual({
      "parent@npm:^1.0.0": "registry",
      "fsevents@npm:~2.3.2": "registry",
      "typescript@npm:^5.0.0": "registry",
      "git-dep@github:x/y": "unsupported",
      "url-dep@npm:1.0.0": "unsupported",
      "proxied@npm:1.0.0": "registry",
    });
    // An older lockfile leaves out the npm: protocol; a builtin patch
    // resolves to the npm entry it patches.
    expect(parsed.resolve("parent@npm:^1.0.0", "fsevents")).toMatchObject({ name: "fsevents", version: "2.3.3" });
    expect(parsed.resolve("parent@npm:^1.0.0", "typescript")).toMatchObject({ name: "typescript", version: "5.4.5" });
    expect(parsed.resolve("parent@npm:^1.0.0", "sibling")).toBeUndefined();
    expect(parsed.resolve("parent@npm:^1.0.0", "url-dep")).toMatchObject({ kind: "unsupported" });
    expect(parsed.projects.map((project) => project.path)).toEqual([
      "sibling@workspace:^, sibling@workspace:packages/sibling",
    ]);
  });

  it("refuses a pre-2.0 metadata version, too many entries and YAML aliases", () => {
    expect(failure(() => parse('__metadata:\n  version: 3\n\n"a@npm:1.0.0":\n  resolution: "a@npm:1.0.0"\n'))).toEqual([
      400,
      "wardby_lockfile_unsupported",
    ]);
    expect(failure(() => parse(berry, 4))).toEqual([413, "wardby_lockfile_too_large"]);
    expect(
      failure(() => parse('__metadata:\n  version: 8\n\nx: &x\n  resolution: "a@npm:1.0.0"\n"a@npm:1.0.0": *x\n')),
    ).toEqual([400, "wardby_bad_request"]);
  });
});

describe("normalizeYarnLockfile", () => {
  it("rewrites a classic lockfile's proxy URLs to yarn's registry, keeping the sha1 fragment", () => {
    const before = [
      "# yarn lockfile v1",
      "",
      '"@s/a@^1.0.0":',
      '  version "1.0.0"',
      `  resolved "${PROXY}-/tarball/%40s%2Fa/1.0.0#0123456789abcdef0123456789abcdef01234567"`,
      "",
      "b@^2.0.0:",
      '  version "2.0.0"',
      `  resolved "${PROXY}b/-/b-2.0.0.tgz"`,
      "",
      "c@^3.0.0:",
      '  version "3.0.0"',
      '  resolved "https://registry.npmjs.org/c/-/c-3.0.0.tgz#aa"',
      "",
    ].join("\n");
    expect(normalizeYarnLockfile(before, PROXY)).toBe(
      [
        "# yarn lockfile v1",
        "",
        '"@s/a@^1.0.0":',
        '  version "1.0.0"',
        '  resolved "https://registry.yarnpkg.com/@s/a/-/a-1.0.0.tgz#0123456789abcdef0123456789abcdef01234567"',
        "",
        "b@^2.0.0:",
        '  version "2.0.0"',
        '  resolved "https://registry.yarnpkg.com/b/-/b-2.0.0.tgz"',
        "",
        "c@^3.0.0:",
        '  version "3.0.0"',
        '  resolved "https://registry.npmjs.org/c/-/c-3.0.0.tgz#aa"',
        "",
      ].join("\n"),
    );
    const real = fixture("yarn-v1.lock");
    expect(normalizeYarnLockfile(real, PROXY)).toBe(real);
  });

  it("drops a Berry resolution's __archiveUrl when it points at the proxy, keeping other parameters", () => {
    const proxied = encodeURIComponent(`${PROXY}-/tarball/a/1.0.0`);
    const before = [
      "__metadata:",
      "  version: 8",
      "",
      '"a@npm:^1.0.0":',
      `  resolution: "a@npm:1.0.0::__archiveUrl=${proxied}"`,
      '"b@npm:^1.0.0":',
      `  resolution: "b@npm:1.0.0::__archiveUrl=${proxied}&other=1"`,
      '"c@npm:^1.0.0":',
      `  resolution: "c@npm:1.0.0::other=1&__archiveUrl=${proxied}"`,
      '"d@npm:^1.0.0":',
      '  resolution: "d@npm:1.0.0::__archiveUrl=https%3A%2F%2Fexample.com%2Fd.tgz"',
      "",
    ].join("\n");
    expect(normalizeYarnLockfile(before, PROXY)).toBe(
      [
        "__metadata:",
        "  version: 8",
        "",
        '"a@npm:^1.0.0":',
        '  resolution: "a@npm:1.0.0"',
        '"b@npm:^1.0.0":',
        '  resolution: "b@npm:1.0.0::other=1"',
        '"c@npm:^1.0.0":',
        '  resolution: "c@npm:1.0.0::other=1"',
        '"d@npm:^1.0.0":',
        '  resolution: "d@npm:1.0.0::__archiveUrl=https%3A%2F%2Fexample.com%2Fd.tgz"',
        "",
      ].join("\n"),
    );
    const real = fixture("yarn-berry.lock");
    expect(normalizeYarnLockfile(real, PROXY)).toBe(real);
  });
});
