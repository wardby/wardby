const PROXY = "http://wardby-proxy:8787/registry/pypi/";
const parse = (body: string, maxEntries = 100) => parsePypiLockfile(body, { maxEntries, proxyRegistryUrl: PROXY });
const summary = (body: string) => parse(body).entries.map((entry) => `${entry.kind}:${entry.name}@${entry.version}`);

describe("pinned requirements files", () => {
  it("reads every exact pin, with continuations, hashes, extras, markers and comments", () => {
    const body = [
      "# This file is autogenerated by pip-compile",
      "--index-url https://pypi.org/simple",
      "-r base.txt",
      "Annotated_Doc==0.0.5 \\",
      "    --hash=sha256:aaaa \\",
      "    --hash=sha256:bbbb",
      "    # via fastapi",
      "psycopg[binary]==3.3.6 ; python_version >= '3.10'  # via -r requirements.in",
      "pytest===9.1.1",
      "requests>=2  # not a pin: resolved the usual way",
      "numpy==1.*",
      "-e .",
      "./vendor/local-pkg",
      "",
    ].join("\n");
    expect(summary(body)).toEqual(["registry:annotated-doc@0.0.5", "registry:psycopg@3.3.6", "registry:pytest@9.1.1"]);
    const lockfile = parse(body);
    expect(lockfile.integrity).toBe("registry");
    expect(lockfile.projects).toEqual([]);
  });

  it("refuses a direct reference and an invalid version as unsupported entries", () => {
    expect(summary("mypkg @ https://example.com/mypkg-1.0.tar.gz\nfoo==not a version\n")).toEqual([
      "unsupported:mypkg@url",
    ]);
    expect(summary("foo==1.0.0.dev-bad!\n")).toEqual(["unsupported:foo@1.0.0.dev-bad!"]);
  });

  it("resolves a dependency to every pin of its name (marker-split pins)", () => {
    const lockfile = parse("numpy==1.26.4 ; python_version < '3.13'\nnumpy==2.1.0 ; python_version >= '3.13'\n");
    expect(lockfile.resolveAll!("anything@1", "numpy").map((entry) => entry.version)).toEqual(["1.26.4", "2.1.0"]);
    expect(lockfile.resolve("anything@1", "numpy")?.version).toBe("1.26.4");
    expect(lockfile.resolveAll!("anything@1", "scipy")).toEqual([]);
  });

  it("stops at REGISTRY_PLAN_MAX_ENTRIES", () => {
    expect(() => parse("a==1\nb==1\nc==1\n", 2)).toThrow(
      expect.objectContaining({ status: 413, code: "wardby_lockfile_too_large" }),
    );
  });
});

const UV_LOCK = `version = 1
revision = 3
requires-python = ">=3.12"

[[package]]
name = "anyio"
version = "4.15.1"
source = { registry = "https://pypi.org/simple" }
dependencies = [
    { name = "idna" },
    { name = "typing-extensions", version = "4.16.0", marker = "python_full_version < '3.15'" },
]

[[package]]
name = "demo-app"
version = "0.1.0"
source = { editable = "." }
dependencies = [
    { name = "anyio" },
    { name = "private-lib" },
]

[package.optional-dependencies]
test = [
    { name = "pytest" },
]

[[package]]
name = "idna"
version = "3.20"
source = { registry = "${PROXY}simple/" }

[[package]]
name = "private-lib"
version = "1.0"
source = { registry = "https://pypi.example.com/simple" }

[[package]]
name = "pytest"
version = "9.1.1"
source = { git = "https://github.com/pytest-dev/pytest?rev=abc#abc" }

[[package]]
name = "typing-extensions"
version = "4.15.0"
source = { registry = "https://pypi.org/simple" }

[[package]]
name = "typing-extensions"
version = "4.16.0"
source = { registry = "https://pypi.org/simple" }
`;

describe("uv.lock", () => {
  it("reads PyPI and proxy packages as entries, its own project as a project, and the rest as unsupported", () => {
    expect(summary(UV_LOCK)).toEqual([
      "registry:anyio@4.15.1",
      "registry:idna@3.20",
      "unsupported:private-lib@1.0",
      "unsupported:pytest@9.1.1",
      "registry:typing-extensions@4.15.0",
      "registry:typing-extensions@4.16.0",
    ]);
    const lockfile = parse(UV_LOCK);
    expect(lockfile.integrity).toBe("registry");
    expect(lockfile.projects).toEqual([
      {
        path: "demo-app@0.1.0",
        dependencies: ["anyio", "private-lib", "pytest"].map((name) => ({ key: name, name, range: "*" })),
      },
    ]);
    expect(lockfile.entries.find((entry) => entry.name === "pytest")?.unsupportedReason).toMatch(/git/);
    expect(lockfile.entries.find((entry) => entry.name === "private-lib")?.unsupportedReason).toMatch(/another/);
  });

  it("resolves a name locked at two versions to the one the parent names", () => {
    const lockfile = parse(UV_LOCK);
    expect(lockfile.resolve("anyio@4.15.1", "typing-extensions")?.version).toBe("4.16.0");
    expect(lockfile.resolve("anyio@4.15.1", "idna")?.version).toBe("3.20");
    expect(lockfile.resolve("anyio@4.15.1", "nothing")).toBeUndefined();
  });

  it("refuses other lock versions, invalid TOML, Poetry and pylock.toml files", () => {
    const code = (body: string) => {
      try {
        parse(body);
        return "parsed";
      } catch (error) {
        return error instanceof RegistryError ? `${error.status} ${error.code}` : "threw";
      }
    };
    expect(code(UV_LOCK.replace("version = 1\n", "version = 2\n"))).toBe("400 wardby_lockfile_unsupported");
    expect(code("version = 1\n[[package]\nname = 'x'\n")).toBe("400 wardby_bad_request");
    expect(code("# This file is automatically @generated by Poetry 2.1.1\n[[package]]\nname = 'x'\n")).toBe(
      "400 wardby_lockfile_unsupported",
    );
    expect(code('lock-version = "1.0"\n[[packages]]\nname = "x"\n')).toBe("400 wardby_lockfile_unsupported");
  });
});

/** A fake PyPI JSON API answering `/pypi/<name>/<version>/json`. */
function jsonApi(releases: Record<string, { requires?: string[] | null; files?: object[] }>): UpstreamFetch {
  return async (url) => {
    const match = url.match(/^https:\/\/pypi\.org\/pypi\/([^/]+)\/([^/]+)\/json$/);
    const key = match ? `${decodeURIComponent(match[1])}@${decodeURIComponent(match[2])}` : "";
    const release = releases[key];
    if (!match || !release) return new Response("{}", { status: 404 });
    const [name, version] = key.split("@");
    return Response.json({
      info: { name: name.toUpperCase(), version, requires_dist: release.requires ?? null },
      urls: release.files ?? [],
    });
  };
}
const wheel = (filename: string, uploaded: string, extra: object = {}) => ({
  packagetype: "bdist_wheel",
  filename,
  url: `https://files.pythonhosted.org/packages/ab/cd/${filename}`,
  yanked: false,
  upload_time_iso_8601: uploaded,
  digests: { sha256: "a".repeat(64) },
  ...extra,
});

describe("PyPI release facts", () => {
  it("reads dependency lines with their extras and extra gates, and the earliest wheel", async () => {
    const fact = await fetchPypiVersionFact(
      "demo",
      "1.0",
      jsonApi({
        "demo@1.0": {
          requires: [
            "starlette>=0.46.0",
            "uvicorn[standard] (>=0.30) ; extra == 'web'",
            'pytest ; extra == "test"',
            "localdep @ https://example.com/x.whl",
            "demo[web] ; extra == 'all'",
          ],
          files: [
            wheel("demo-1.0-cp312-cp312-manylinux_2_17_x86_64.whl", "2026-09-02T00:00:00Z"),
            wheel("demo-1.0-py3-none-any.whl", "2026-09-01T00:00:00.123456Z"),
            wheel("demo-1.0-py2-none-any.whl", "2026-08-01T00:00:00Z", { yanked: true }),
            { packagetype: "sdist", filename: "demo-1.0.tar.gz", url: "https://x/demo-1.0.tar.gz" },
          ],
        },
      }),
    );
    expect(fact).toMatchObject({
      name: "demo",
      version: "1.0",
      publishedAt: new Date("2026-09-01T00:00:00.123Z"),
      downloadUrl: "https://files.pythonhosted.org/packages/ab/cd/demo-1.0-py3-none-any.whl",
      integrity: `sha256-${Buffer.from("a".repeat(64), "hex").toString("base64")}`,
    });
    expect(fact!.dependencies).toEqual([
      { key: "starlette", name: "starlette", range: ">=0.46.0" },
      { key: "uvicorn", name: "uvicorn", range: ">=0.30", extras: ["standard"], when: ["web"] },
      { key: "pytest", name: "pytest", range: "*", when: ["test"] },
      { key: "demo", name: "demo", range: "*", extras: ["web"], when: ["all"] },
    ]);
  });

  it("refuses a release with no wheel, and answers null for one PyPI doesn't have or names differently", async () => {
    const api = jsonApi({
      "sdistonly@1.0": { files: [{ packagetype: "sdist", filename: "sdistonly-1.0.tar.gz", url: "https://x" }] },
    });
    await expect(fetchPypiVersionFact("sdistonly", "1.0", api)).rejects.toMatchObject({
      status: 403,
      code: "wardby_file_not_allowed",
    });
    await expect(fetchPypiVersionFact("missing", "1.0", api)).resolves.toBeNull();
    const renamed: UpstreamFetch = async () =>
      Response.json({ info: { name: "other", version: "1.0" }, urls: [wheel("other-1.0-py3-none-any.whl", "x")] });
    await expect(fetchPypiVersionFact("demo", "1.0", renamed)).resolves.toBeNull();
  });
});

describe("PyPI plan edges", () => {
  const fact: VersionFact = {
    name: "demo",
    version: "1.0",
    publishedAt: new Date(),
    integrity: "sha256-x",
    downloadUrl: "https://files.pythonhosted.org/x.whl",
    dependencies: [
      { key: "starlette", name: "starlette", range: ">=0.46.0" },
      { key: "uvicorn", name: "uvicorn", range: ">=0.30", extras: ["standard"], when: ["web"] },
      { key: "pytest", name: "pytest", range: "*", when: ["test"] },
      { key: "demo", name: "demo", range: "*", extras: ["web"], when: ["all"] },
      { key: "never", name: "never", range: "*", when: [] },
    ],
  };
  const names = (extras: string[]) =>
    pypiDependenciesOf(fact, extras).map((dependency) =>
      dependency.extras ? `${dependency.name}[${dependency.extras.join(",")}]` : dependency.name,
    );

  it("follows ungated lines only for a plain install, with every dependency bare", () => {
    expect(names([])).toEqual(["starlette"]);
  });

  it("follows the lines an install's extras gate, its self-referencing extras too", () => {
    expect(names(["test"])).toEqual(["starlette", "pytest"]);
    expect(names(["all"])).toEqual(["starlette", "uvicorn[standard]"]);
  });

  it("checks a locked version against the line's specifier, pre-releases included", () => {
    expect(pypiEdgeSatisfies("1.2.0", "*")).toBe(true);
    expect(pypiEdgeSatisfies("1.2.0", ">=1,<2")).toBe(true);
    expect(pypiEdgeSatisfies("2.0.0", ">=1,<2")).toBe(false);
    expect(pypiEdgeSatisfies("2.0rc1", ">=1.5")).toBe(true);
    expect(pypiEdgeSatisfies("1.0", "not a specifier")).toBe(false);
  });

  it("reads a dependency line's specifier, in either spelling, and drops direct references", () => {
    expect(requirementLine("foo (>=1.0,<2)")).toMatchObject({ name: "foo", range: ">=1.0,<2", gate: null });
    expect(requirementLine("Foo_Bar[x, Y]>=1 ; extra == 'z'")).toMatchObject({
      name: "foo-bar",
      extras: ["x", "y"],
      range: ">=1",
      gate: ["z"],
    });
    expect(requirementLine("foo @ https://example.com/foo.whl")?.range).toBeNull();
    expect(requirementLine("foo")?.range).toBe("*");
  });
});

describe("uv.lock URLs at collection", () => {
  it("maps the proxy's index and file URLs back to PyPI's, and leaves everything else alone", () => {
    const written = [
      `source = { registry = "${PROXY}simple/" }`,
      `sdist = { url = "${PROXY}files/annotated-doc/annotated_doc-0.0.5.tar.gz", hash = "sha256:c7" }`,
      `    { url = "http://wardby:rrg_FAKE@wardby-proxy:8787/registry/pypi/files/six/six-1.17.0-py2.py3-none-any.whl", hash = "sha256:47" },`,
      `    { url = "${PROXY}files/torch/torch-2.5.0%2Bcpu-cp312-cp312-linux_x86_64.whl" },`,
      `source = { registry = "https://pypi.example.com/simple" }`,
    ].join("\n");
    const normalized = normalizeUvLock(written, PROXY);
    expect(normalized.split("\n")).toEqual([
      'source = { registry = "https://pypi.org/simple" }',
      'sdist = { url = "https://files.pythonhosted.org/packages/source/a/annotated-doc/annotated_doc-0.0.5.tar.gz", hash = "sha256:c7" }',
      '    { url = "https://files.pythonhosted.org/packages/py2.py3/s/six/six-1.17.0-py2.py3-none-any.whl", hash = "sha256:47" },',
      '    { url = "https://files.pythonhosted.org/packages/cp312/t/torch/torch-2.5.0+cpu-cp312-cp312-linux_x86_64.whl" },',
      'source = { registry = "https://pypi.example.com/simple" }',
    ]);
    expect(normalized).not.toContain("rrg_FAKE");
    expect(normalizeUvLock(normalized, PROXY)).toBe(normalized);
  });

  it("builds PyPI's redirecting path only for names and filenames it can read", () => {
    expect(publicFileUrl("six", "six-1.17.0-py2.py3-none-any.whl")).toBe(
      "https://files.pythonhosted.org/packages/py2.py3/s/six/six-1.17.0-py2.py3-none-any.whl",
    );
    expect(publicFileUrl("six", "six.exe")).toBeUndefined();
    expect(publicFileUrl("../x", "x-1.0.tar.gz")).toBeUndefined();
    expect(publicFileUrl("six", "six-1.0-py3.whl")).toBeUndefined();
  });
});
